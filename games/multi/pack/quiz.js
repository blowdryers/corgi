function makeQuiz(key,title,blurb,make,time,theme){
  return{
    start(){this.state='menu';this.best=store(key);this.btn=[]},
    begin(){this.qs=make();this.i=0;this.score=0;this.right=0;this.state='q';this.load()},
    load(){const q=this.qs[this.i];this.opts=shuffle([q.a,...q.w]);this.t=time;this.pick=-1;this.fb=0},
    rects(){const w=380,h=78,g=16,ox=(W-2*w-g)/2,oy=300;return[0,1,2,3].map(i=>({x:ox+(i%2)*(w+g),y:oy+(i>>1)*(h+g),w,h}))},
    answer(k){
      if(this.state!=='q'||this.pick!==-1)return;this.pick=k;
      if(this.opts[k]===this.qs[this.i].a){this.right++;this.score+=100+Math.round(this.t/time*100);tone(660,.1,.05,'triangle',990)}else tone(180,.25,.05,'sawtooth',110);
      this.fb=1.3;
    },
    down(){if(this.state==='menu'||this.state==='over'&&this.endT>.5){this.begin();return}this.rects().forEach((r,i)=>{if(inRect(mouse,r))this.answer(i)})},
    key(c){const d=digitOf(c);if(d&&+d>=1&&+d<=4)this.answer(+d-1);if((c==='Space'||c==='Enter')&&(this.state==='menu'||this.state==='over'&&this.endT>.5))this.begin()},
    update(dt){
      if(this.state==='over'){this.endT+=dt;return}
      if(this.state!=='q')return;
      if(this.pick===-1){this.t-=dt;if(this.t<=0){this.t=0;this.pick=-2;this.fb=1.3;tone(180,.25,.05,'sawtooth',110)}return}
      this.fb-=dt;if(this.fb<=0){this.i++;if(this.i>=this.qs.length){this.state='over';this.endT=0;this.best=best(key,this.score)}else this.load()}
    },
    draw(){
      bg(theme);
      if(this.state==='q'||this.state==='over'&&this.qs){
        const q=this.qs[Math.min(this.i,this.qs.length-1)];
        text('question '+Math.min(this.i+1,this.qs.length)+' of '+this.qs.length,30,34,16,'rgba(255,255,255,.6)','left');text('score '+this.score,W-30,34,18,'#fff','right');
        timerBar(30,56,W-60,8,this.t/time,this.t<4?'#f87171':'#5eead4');
        wrapText(q.q,W/2,120,800,30,'#fff',40);
        this.rects().forEach((r,i)=>{
          const o=this.opts[i];let col=null;
          if(this.pick!==-1){if(o===q.a)col='#15803d';else if(i===this.pick)col='#b91c1c';else col='rgba(255,255,255,.06)'}
          button(r,(i+1)+'   '+o,col,22);
        });
      }
      if(this.state==='menu')overlay(title,blurb,'10 questions, faster answers score more. click to start. best '+this.best);
      if(this.state==='over'&&this.endT>.5)overlay(this.right+' / '+this.qs.length+' correct','score '+this.score+'  best '+this.best,'click to play again');
    }
  };
}

