const QMath={
  start(){this.state='menu';this.best=store('qmath')},
  begin(){this.state='q';this.time=60;this.score=0;this.streak=0;this.n=0;this.inp='';this.flash=0;this.gen()},
  gen(){
    const lv=Math.min(5,1+(this.n/5|0)),op=pick(lv<2?['+','-']:lv<3?['+','-','x']:['+','-','x','/']);let a,b,ans;
    const top=[0,10,20,50,100,200][lv];
    if(op==='+'){a=irnd(2,top);b=irnd(2,top);ans=a+b}
    if(op==='-'){a=irnd(2,top);b=irnd(1,a);ans=a-b}
    if(op==='x'){a=irnd(2,lv<4?9:12);b=irnd(2,lv<4?9:15);ans=a*b}
    if(op==='/'){b=irnd(2,12);ans=irnd(2,12);a=b*ans}
    this.q=a+' '+(op==='x'?'×':op==='/'?'÷':op)+' '+b;this.ans=ans;
  },
  typing:true,
  KP:['7','8','9','4','5','6','1','2','3','<','0','>'],
  kr(i){return{x:620+(i%3)*94,y:150+(i/3|0)*94,w:84,h:84}},
  press(k){
    if(this.state!=='q')return;
    if(k==='<'){this.inp=this.inp.slice(0,-1);return}
    if(k==='>'){if(this.inp)this.submit();return}
    if(this.inp.length<5)this.inp+=k;
    if(+this.inp===this.ans)this.submit();
  },
  submit(){
    if(+this.inp===this.ans){this.n++;this.streak++;this.score+=10+Math.min(this.streak,10);this.flash=.25;tone(700+Math.min(this.streak,10)*30,.06,.05,'triangle')}
    else{this.streak=0;this.time=Math.max(0,this.time-3);this.flash=-.3;tone(160,.2,.05,'sawtooth')}
    this.inp='';this.gen();
  },
  down(){if(this.state==='menu'||this.state==='over'&&this.endT>.5){this.begin();return}this.KP.forEach((k,i)=>{if(inRect(mouse,this.kr(i)))this.press(k)})},
  key(c){if(this.state!=='q'){if((c==='Space'||c==='Enter')&&(this.state==='menu'||this.endT>.5))this.begin();return}const d=digitOf(c);if(d!==null)this.press(d);if(c==='Backspace')this.press('<');if(c==='Enter'||c==='NumpadEnter')this.press('>')},
  update(dt){
    if(this.state==='over'){this.endT+=dt;return}
    if(this.state!=='q')return;
    if(this.flash>0)this.flash=Math.max(0,this.flash-dt);if(this.flash<0)this.flash=Math.min(0,this.flash+dt);
    this.time-=dt;if(this.time<=0){this.time=0;this.state='over';this.endT=0;this.best=best('qmath',this.score)}
  },
  draw(){
    bg(this.flash>0?'#14532d':this.flash<0?'#7f1d1d':'#0c4a6e');
    if(this.state!=='menu'){
      text('score '+this.score,96,34,18,'#fff','left');text(Math.ceil(this.time)+'s',W/2,34,24,this.time<10?'#fca5a5':'#fff');text('streak '+this.streak,W-30,34,18,'#bae6fd','right');
      text(this.q+' =',300,230,64,'#fff');
      rr(150,290,300,90,14,'rgba(255,255,255,.1)');text(this.inp||'?',300,337,52,this.inp?'#fff':'rgba(255,255,255,.3)');
      text('type the answer. correct answers submit themselves',300,420,14,'rgba(255,255,255,.55)');text('wrong answers cost 3 seconds',300,442,14,'rgba(255,255,255,.55)');
      this.KP.forEach((k,i)=>button(this.kr(i),k==='<'?'del':k==='>'?'ok':k,null,26));
    }
    if(this.state==='menu')overlay('Quick Math','solve as many as you can in 60 seconds','it gets harder as you go. click to start. best '+this.best);
    if(this.state==='over'&&this.endT>.5)overlay('Time','solved '+this.n+'  score '+this.score+'  best '+this.best,'click to play again');
  }
};

